LEAD_MAGNET_FILE_RELATIVE_PATH = "lead-magnets/razbor-garderoba.pdf"


class Command(BaseCommand):
    help = "Заполняет базу демо-контентом, совпадающим с тем, что зашит в статике фронтенда"

    def handle(self, *args, **options):
        for data in SERVICES:
            review_data = data.pop("review")
            service, _ = Service.objects.update_or_create(slug=data["slug"], defaults=data)
            Review.objects.update_or_create(
                service=service, author=review_data["author"], defaults={"quote": review_data["quote"]}
            )
            self.stdout.write(f"  услуга: {service.title}")

        for i, data in enumerate(BLOG_POSTS):
            BlogPost.objects.update_or_create(
                slug=data["slug"],
                defaults={
                    **data,
                    "status": BlogPost.Status.PUBLISHED,
                    "published_at": timezone.now() - timezone.timedelta(days=i * 7),
                },
            )
        self.stdout.write(f"  записей блога: {len(BLOG_POSTS)}")

        profile = SiteProfile.load()
        for field, value in SITE_PROFILE.items():
            setattr(profile, field, value)
        if (Path(settings.MEDIA_ROOT) / LEAD_MAGNET_FILE_RELATIVE_PATH).exists():
            profile.lead_magnet_file.name = LEAD_MAGNET_FILE_RELATIVE_PATH
        profile.save()
        self.stdout.write("  профиль сайта обновлён")

        self.stdout.write(self.style.SUCCESS("Готово."))
